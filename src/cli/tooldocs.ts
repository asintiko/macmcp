import { MODE_LABEL } from '../core/permissions.js';
import { type AnyTool, inputJsonSchema, type JsonSchema, TOOL_GROUPS, type ToolGroup, type ToolRegistry } from '../tools/registry.js';
import { VERSION } from '../version.js';

export function inputSchema(tool: AnyTool): JsonSchema {
  return inputJsonSchema(tool);
}

function grouped(registry: ToolRegistry): [ToolGroup, AnyTool[]][] {
  const tools = registry.all();
  return (Object.keys(TOOL_GROUPS) as ToolGroup[]).map((group) => [group, tools.filter((t) => t.group === group)] as [ToolGroup, AnyTool[]]).filter(([, list]) => list.length > 0);
}

function accessLabel(tool: AnyTool): string {
  return tool.access === 'full' ? `${MODE_LABEL.full} only` : 'both permission levels';
}

function describeType(schema: JsonSchema): string {
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (schema.type === 'array') return `${schema.items ? describeType(schema.items) : 'any'}[]`;
  if (schema.type === 'object' && schema.properties) return `object { ${Object.keys(schema.properties).join(', ')} }`;
  const safe = Number.MAX_SAFE_INTEGER;
  const hasMin = schema.minimum !== undefined && schema.minimum > -safe;
  const hasMax = schema.maximum !== undefined && schema.maximum < safe;
  const range = hasMin && hasMax ? ` (${schema.minimum}–${schema.maximum})` : hasMin ? ` (≥ ${schema.minimum})` : hasMax ? ` (≤ ${schema.maximum})` : '';
  return `${schema.type ?? 'any'}${range}`;
}

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Compact listing for the terminal. */
export function renderToolsText(registry: ToolRegistry): string {
  const lines: string[] = [];
  for (const [group, tools] of grouped(registry)) {
    lines.push(`${TOOL_GROUPS[group].title} — ${TOOL_GROUPS[group].summary}`);
    const width = Math.max(...tools.map((t) => t.name.length));
    for (const tool of tools) {
      lines.push(`  ${tool.name.padEnd(width)}  ${tool.title}${tool.access === 'full' ? '  [full access]' : ''}`);
    }
    lines.push('');
  }
  lines.push(`${registry.all().length} tools. "[full access]" tools exist only in ${MODE_LABEL.full} mode.`);
  return lines.join('\n');
}

/** Machine-readable catalogue. */
export function renderToolsJson(registry: ToolRegistry): string {
  return JSON.stringify(
    {
      server: 'mcpclaude',
      version: VERSION,
      tools: registry.all().map((tool) => ({
        name: tool.name,
        title: tool.title,
        group: tool.group,
        access: tool.access,
        requires_macos_desktop: tool.desktop === true,
        description: tool.description,
        input_schema: inputSchema(tool),
        examples: tool.examples,
      })),
    },
    null,
    2,
  );
}

/** The tool reference published as docs/TOOLS.md. Generated; do not edit the file by hand. */
export function renderToolsMarkdown(registry: ToolRegistry): string {
  const out: string[] = [
    '# Tool reference',
    '',
    '<!-- Generated by `npm run docs:tools` from the tool registry. Do not edit by hand. -->',
    '',
    `Every MCP tool offered by mcpclaude ${VERSION}, grouped by purpose. Each entry lists who can`,
    'use it, what it does, its parameters and example calls (the JSON is the `arguments` object',
    'of an MCP `tools/call` request).',
    '',
    `- **Both permission levels** — available in ${MODE_LABEL.project} and ${MODE_LABEL.full} mode. In`,
    `  ${MODE_LABEL.project} mode paths are confined to the project directory and commands are sandboxed.`,
    `- **${MODE_LABEL.full} only** — not listed and refused in ${MODE_LABEL.project} mode.`,
    '',
    'Failed calls return `Error [CODE]: message` (and often a `Hint:` line) with `isError: true`.',
    '',
    '## Contents',
    '',
  ];
  for (const [group, tools] of grouped(registry)) {
    out.push(`- [${TOOL_GROUPS[group].title}](#${TOOL_GROUPS[group].title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}) — ${tools.map((t) => `\`${t.name}\``).join(', ')}`);
  }
  out.push('');

  for (const [group, tools] of grouped(registry)) {
    out.push(`## ${TOOL_GROUPS[group].title}`, '', TOOL_GROUPS[group].summary, '');
    for (const tool of tools) {
      const schema = inputSchema(tool);
      const required = new Set(schema.required ?? []);
      out.push(`### \`${tool.name}\``, '', `**${tool.title}** · ${accessLabel(tool)}${tool.desktop ? ' · needs macOS desktop control' : ''}`, '', tool.description.trim(), '');
      const properties = Object.entries(schema.properties ?? {});
      if (properties.length === 0) {
        out.push('No parameters.', '');
      } else {
        out.push('| Parameter | Type | Required | Default | Description |', '|---|---|---|---|---|');
        for (const [name, property] of properties) {
          const fallback = property.default === undefined ? '—' : `\`${JSON.stringify(property.default)}\``;
          out.push(`| \`${name}\` | ${describeType(property)} | ${required.has(name) ? 'yes' : 'no'} | ${fallback} | ${cell(property.description ?? '')} |`);
        }
        out.push('');
      }
      out.push(tool.examples.length === 1 ? 'Example:' : 'Examples:', '');
      for (const example of tool.examples) {
        if (example.note) out.push(example.note, '');
        out.push('```json', JSON.stringify(example.arguments, null, 2), '```', '');
      }
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}
